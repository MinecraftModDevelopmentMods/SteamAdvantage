package com.mcmoddev.steamadvantage.machines;

import static org.junit.Assert.*;

import cyano.poweradvantage.api.simple.TileEntitySimplePowerMachine;
import java.lang.reflect.Field;
import java.util.*;
import net.minecraft.block.state.IBlockState;
import net.minecraft.init.Bootstrap;
import net.minecraft.profiler.Profiler;
import net.minecraft.util.math.BlockPos;
import net.minecraft.world.World;
import net.minecraft.world.WorldProviderSurface;
import net.minecraft.world.chunk.IChunkProvider;
import org.junit.BeforeClass;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.junit.runners.Parameterized;

@RunWith(Parameterized.class)
public class SteamRedstoneInitializationTest {
    @Parameterized.Parameters(name = "{0}")
    public static Collection<Object[]> machines() {
        return Arrays.asList(new Object[][]{
            {RockCrusherTileEntity.class}, {BlastFurnaceTileEntity.class}
        });
    }

    private final Class<? extends TileEntitySimplePowerMachine> type;
    public SteamRedstoneInitializationTest(Class<? extends TileEntitySimplePowerMachine> type) { this.type = type; }
    @BeforeClass public static void bootstrap() { Bootstrap.register(); }

    @Test public void firstServerTickSamplesTheUnpoweredWorldBeforeUsingTheCache() throws Exception {
        ControlWorld world = new ControlWorld();
        TileEntitySimplePowerMachine machine = machine(world);
        machine.tickUpdate(true);
        assertTrue("The first server tick must read the real control signal", world.samples > 0);
        assertFalse("A fresh cache must not invent a redstone signal", redstone(machine));
    }

    @Test public void firstServerTickHonoursARealPoweredControl() throws Exception {
        ControlWorld world = new ControlWorld();
        world.powered = true;
        TileEntitySimplePowerMachine machine = machine(world);
        machine.tickUpdate(true);
        assertTrue("A default true value alone does not prove a world sample", world.samples > 0);
        assertTrue(redstone(machine));
    }

    @Test public void ordinaryTicksDoNotReplaceTheScheduledControlPolling() throws Exception {
        ControlWorld world = new ControlWorld();
        TileEntitySimplePowerMachine machine = machine(world);
        machine.tickUpdate(true);
        assertFalse(redstone(machine));
        world.powered = true;
        machine.tickUpdate(true);
        assertFalse("After initialization, the cache must wait for its scheduled power update", redstone(machine));
    }

    @Test public void theClientTickDoesNotInitializeAServerControlCache() throws Exception {
        ControlWorld world = new ControlWorld();
        TileEntitySimplePowerMachine machine = machine(world);
        machine.tickUpdate(false);
        assertEquals(0, world.samples);
        assertTrue(redstone(machine));
    }

    @Test public void loadingAnExistingInstanceMakesTheNextServerTickResample() throws Exception {
        ControlWorld world = new ControlWorld();
        TileEntitySimplePowerMachine machine = machine(world);
        machine.tickUpdate(true);
        assertFalse(redstone(machine));
        machine.setWorld(null);
        machine.onLoad();
        machine.setWorld(world);
        world.powered = true;
        world.samples = 0;
        machine.tickUpdate(true);
        assertTrue("A reused tile instance must not retain its old control decision", world.samples > 0);
        assertTrue(redstone(machine));
    }

    private TileEntitySimplePowerMachine machine(ControlWorld world) throws Exception {
        TileEntitySimplePowerMachine result = type.getConstructor().newInstance();
        result.setWorld(world);
        result.setPos(new BlockPos(8, 80, 8));
        return result;
    }

    private boolean redstone(TileEntitySimplePowerMachine machine) throws Exception {
        Field field = type.getDeclaredField("redstone");
        field.setAccessible(true);
        return field.getBoolean(machine);
    }

    private static final class ControlWorld extends World {
        boolean powered;
        int samples;
        ControlWorld() { super(null, null, new WorldProviderSurface(), new Profiler(), false); }
        @Override public boolean isBlockPowered(BlockPos pos) { samples++; return powered; }
        @Override public IBlockState getBlockState(BlockPos pos) { return net.minecraft.init.Blocks.AIR.getDefaultState(); }
        @Override protected boolean isChunkLoaded(int x, int z, boolean allowEmpty) { return true; }
        @Override protected IChunkProvider createChunkProvider() { throw new AssertionError("No chunks may be generated by this control test"); }
    }
}
